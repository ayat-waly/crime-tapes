// Run from any directory: node locales/build.cjs
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
const data = read('game-data.json');
const get = (value, key) => key.replace(/\[(\d+)\]/g, '.$1').split('.').reduce((o,k) => o?.[k], value);
const arabic = /[\u0621-\u064a]/;
function strings(value, prefix = '', result = {}) {
  if (typeof value === 'string' && arabic.test(value)) result[prefix] = value;
  else if (value && typeof value === 'object') Object.entries(value).forEach(([k,v]) => strings(v, Array.isArray(value) ? `${prefix}[${k}]` : prefix ? `${prefix}.${k}` : k, result));
  return result;
}
const catalog = {ui: read('locales/ui.en.json'), media: read('locales/media.en.json'), cases: {}, coverage: {}};
for (const name of fs.readdirSync(__dirname).filter(n => /^c\d+\.en\.json$/.test(n))) {
  const translation = read('locales/' + name);
  const source = data.cases.find(c => c.id === translation.caseId);
  assert(source, 'Unknown case: ' + translation.caseId);
  const entries = [];
  for (const [key,en] of Object.entries(translation.strings)) {
    const ar = get(source, key);
    assert(typeof ar === 'string', 'Unknown string path: ' + source.id + '.' + key);
    assert(typeof en === 'string' && en.trim() && !arabic.test(en), 'Missing English text: ' + key);
    entries.push({path:key, ar, en});
  }
  const missing = Object.keys(strings(source)).filter(k => !Object.hasOwn(translation.strings,k));
  catalog.cases[source.id] = entries;
  catalog.coverage[source.id] = {translated:entries.length, missing};
}
for (const [ar,en] of Object.entries(catalog.media)) {
  assert(fs.existsSync(path.join(root, ar)), 'Missing Arabic asset: ' + ar);
  assert(fs.existsSync(path.join(root, en)), 'Missing English asset: ' + en);
}
fs.writeFileSync(path.join(__dirname, 'catalog.en.js'), '// Generated by locales/build.cjs. Edit the JSON sources.\nwindow.CT_EN = ' + JSON.stringify(catalog) + ';\n');
console.log(JSON.stringify({cases:catalog.coverage, media:Object.keys(catalog.media).length},null,2));
